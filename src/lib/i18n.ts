export function getAppLanguage(): AppLanguage {
  return currentLanguage;
}

export async function setAppLanguage(language: AppLanguage): Promise<void> {
  currentLanguage = language;
  try {
    await AsyncStorage.setItem(STORAGE_KEY, language);
  } finally {
    listeners.forEach((listener) => listener(language));
  }
}

export function t(
  key: string,
  params: Record<string, string | number> = {},
  language = currentLanguage,
): string {
  const template =
    (messages[language] as Record<string, string>)[key] ??
    (messages.en as Record<string, string>)[key] ??
    key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}

export function useLanguage() {
  const [language, setLanguageState] = useState<AppLanguage>(currentLanguage);

  useEffect(() => {
    const listener = (next: AppLanguage) => setLanguageState(next);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);

  const setLanguage = useCallback(
    (next: AppLanguage) => setAppLanguage(next),
    [],
  );

  return {
    language,
    setLanguage,
    t: (key: string, params?: Record<string, string | number>) =>
      t(key, params, language),
  };
}

export async function initializeLanguage(): Promise<AppLanguage> {
  if (initialized) return currentLanguage;
  initialized = true;
  try {
    const saved = await AsyncStorage.getItem(STORAGE_KEY);
    const deviceLanguage = getLocales()[0]?.languageCode;
    currentLanguage =
      saved === 'en' || saved === 'es'
        ? saved
        : deviceLanguage === 'es'
          ? 'es'
          : 'en';
  } catch {
    currentLanguage = 'en';
  }
  listeners.forEach((listener) => listener(currentLanguage));
  return currentLanguage;
}
